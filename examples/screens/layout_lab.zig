const std = @import("std");
const kit = @import("../kit.zig");
const zui = kit.zui;
const zui_reflect = kit.zui_reflect;
const Ui = kit.Ui;
const Shell = kit.Shell;

const max_children = 6;

const Container = struct {
    direction: zui.Direction = .left_to_right,
    align_x: zui.Alignment = .start,
    align_y: zui.Alignment = .center,
    child_gap: f32 = 12,
    padding: f32 = 16,
    children: u8 = 4,
    show_sizes: bool = true,

    pub const zui_inspector: zui_reflect.Options(@This()) = .{ .fields = .{
        .align_x = .{ .label = "Align x" },
        .align_y = .{ .label = "Align y" },
        .child_gap = .{ .min = 0, .max = 48, .step = 1 },
        .padding = .{ .min = 0, .max = 64, .step = 1 },
        .children = .{ .min = 1, .max = max_children },
    } };
};

const Rule = enum {
    fit,
    grow,
    fixed,
    percent,

    fn next(rule: Rule) Rule {
        return @enumFromInt((@as(u8, @intFromEnum(rule)) + 1) % 4);
    }
};

/// One slider per axis drives whichever rule is chosen, so the inspector
/// needs no rule-specific fields.
const Child = struct {
    width: Rule = .fit,
    width_amount: f32 = 0.5,
    height: Rule = .fit,
    height_amount: f32 = 0.5,

    pub const zui_inspector: zui_reflect.Options(@This()) = .{ .fields = .{
        .width_amount = .{ .label = "  amount", .min = 0, .max = 1, .step = 0.01 },
        .height_amount = .{ .label = "  amount", .min = 0, .max = 1, .step = 0.01 },
    } };
};

fn sizingOf(rule: Rule, amount: f32) zui.Sizing {
    return switch (rule) {
        .fit => .fit,
        .grow => .growWeighted(0.25 + amount * 3.75),
        .fixed => .fixed(@round(40 + amount * 260)),
        .percent => .percent(@max(0.05, amount)),
    };
}

fn describeSizing(buffer: []u8, rule: Rule, amount: f32) []const u8 {
    const sizing = sizingOf(rule, amount);
    return switch (rule) {
        .fit => std.fmt.bufPrint(buffer, ".fit", .{}),
        .grow => std.fmt.bufPrint(buffer, ".growWeighted({d:.2})", .{sizing.amount}),
        .fixed => std.fmt.bufPrint(buffer, ".fixed({d:.0})", .{sizing.amount}),
        .percent => std.fmt.bufPrint(buffer, ".percent({d:.2})", .{sizing.amount}),
    } catch "?";
}

const default_children = [max_children]Child{
    .{ .width = .fixed, .width_amount = 0.2 },
    .{ .width = .grow, .width_amount = 0.2, .height = .grow },
    .{},
    .{ .width = .grow, .width_amount = 0.6, .height = .percent, .height_amount = 0.6 },
    .{ .width = .percent, .width_amount = 0.15 },
    .{},
};

pub const LayoutLab = struct {
    container: Container = .{},
    children: [max_children]Child = default_children,

    pub fn declare(self: *LayoutLab, ui: *Ui, shell: *const Shell) void {
        ui.open(.{ .layout = .{ .sizing = .grow_both, .child_gap = 16 } });
        defer ui.close();
        self.controls(ui, shell);
        {
            ui.open(.{ .layout = .{ .direction = .top_to_bottom, .sizing = .grow_both, .child_gap = 16 } });
            defer ui.close();
            self.preview(ui, shell);
            self.code(ui, shell);
        }
    }

    fn controls(self: *LayoutLab, ui: *Ui, shell: *const Shell) void {
        ui.open(.{
            .id = .of("lab.controls"),
            .layout = .{ .direction = .top_to_bottom, .sizing = .{ .width = .fixed(380), .height = .grow }, .padding = .all(14), .child_gap = 10 },
            .decoration = .{ .background = shell.palette.surface, .border = .{ .color = shell.palette.border, .widths = .all(1) }, .corner_radius = .all(10) },
            .scroll = .{},
        });
        defer ui.close();
        shell.label(ui, .heading, "Container");
        shell.label(ui, .caption, "Generated by zui_reflect.inspector from a plain struct.");
        _ = zui_reflect.inspector(shell.widgets, ui, .of("lab.container"), &self.container);
        for (self.children[0..self.container.children], 0..) |*child, index| {
            shell.divider(ui);
            ui.open(.{ .layout = .{ .child_gap = 8, .child_alignment = .{ .y = .center } } });
            ui.box(.{ .layout = .{ .sizing = .{ .width = .fixed(12), .height = .fixed(12) } }, .decoration = .{ .background = childColor(index), .corner_radius = .all(6) } });
            shell.print(ui, .body, "Child {d}", .{index + 1});
            ui.close();
            _ = zui_reflect.inspector(shell.widgets, ui, .indexed("lab.child", index), child);
        }
        if (shell.widgets.button(ui, .of("lab.reset"), "Reset", .{})) self.* = .{};
    }

    fn preview(self: *LayoutLab, ui: *Ui, shell: *const Shell) void {
        const palette = shell.palette;
        const container = self.container;
        ui.open(.{
            .layout = .{ .direction = .top_to_bottom, .sizing = .grow_both, .padding = .all(14), .child_gap = 10 },
            .decoration = .{ .background = palette.surface, .border = .{ .color = palette.border, .widths = .all(1) }, .corner_radius = .all(10) },
        });
        defer ui.close();
        {
            ui.open(.{ .layout = .{ .sizing = .{ .width = .grow }, .child_gap = 10, .child_alignment = .{ .y = .center } } });
            defer ui.close();
            shell.label(ui, .heading, "Preview");
            shell.label(ui, .caption, "click a child to cycle its width rule; sizes are ui.rectOf() from the frame before");
        }
        const padding_color = palette.warn.mix(palette.surface, 0.85);
        ui.open(.{
            .id = .of("lab.container_under_test"),
            .layout = .{
                .direction = container.direction,
                .sizing = .grow_both,
                .padding = .all(container.padding),
                .child_gap = container.child_gap,
                .child_alignment = .{ .x = container.align_x, .y = container.align_y },
            },
            .decoration = .{ .background = padding_color, .border = .{ .color = palette.warn, .widths = .all(1) }, .corner_radius = .all(4) },
            .clip = .both,
        });
        defer ui.close();
        for (self.children[0..container.children], 0..) |*child, index| {
            const id: zui.Id = .indexed("lab.preview", index);
            if (ui.clicked(id)) child.width = child.width.next();
            const hovered = ui.hovered(id);
            const color = childColor(index);
            ui.open(.{
                .id = id,
                .interactive = true,
                .cursor = .pointer,
                .layout = .{
                    .direction = .top_to_bottom,
                    .sizing = .{ .width = sizingOf(child.width, child.width_amount), .height = sizingOf(child.height, child.height_amount) },
                    .padding = .all(8),
                    .child_gap = 4,
                },
                .decoration = .{ .background = if (hovered) color else color.mix(palette.background, 0.25), .border = .{ .color = palette.text.mix(color, 0.5), .widths = .all(if (hovered) 2 else 0) }, .corner_radius = .all(6) },
                .clip = .both,
            });
            defer ui.close();
            var width_buffer: [32]u8 = undefined;
            var height_buffer: [32]u8 = undefined;
            shell.printColored(ui, .caption, palette.on_accent, "#{d} w {s}", .{ index + 1, describeSizing(&width_buffer, child.width, child.width_amount) });
            shell.printColored(ui, .caption, palette.on_accent, "   h {s}", .{describeSizing(&height_buffer, child.height, child.height_amount)});
            if (container.show_sizes) if (ui.rectOf(id)) |rect| {
                shell.printColored(ui, .tiny, palette.on_accent, "{d:.0} x {d:.0}", .{ rect.width, rect.height });
            };
        }
    }

    fn code(self: *LayoutLab, ui: *Ui, shell: *const Shell) void {
        const container = self.container;
        var buffer: [2048]u8 = undefined;
        var writer: std.Io.Writer = .fixed(&buffer);
        writer.print("ui.open(.{{ .layout = .{{ .direction = .{t}, .sizing = .grow_both,\n", .{container.direction}) catch {};
        writer.print("    .padding = .all({d:.0}), .child_gap = {d:.0}, .child_alignment = .{{ .x = .{t}, .y = .{t} }} }} }});\n", .{ container.padding, container.child_gap, container.align_x, container.align_y }) catch {};
        for (self.children[0..container.children]) |child| {
            var width_buffer: [32]u8 = undefined;
            var height_buffer: [32]u8 = undefined;
            writer.print("ui.box(.{{ .layout = .{{ .sizing = .{{ .width = {s}, .height = {s} }} }} }});\n", .{
                describeSizing(&width_buffer, child.width, child.width_amount),
                describeSizing(&height_buffer, child.height, child.height_amount),
            }) catch {};
        }
        writer.print("ui.close();", .{}) catch {};

        shell.openCard(ui, "The same layout, in Zig", .{ .width = .grow });
        defer ui.close();
        ui.open(.{
            .layout = .{ .sizing = .{ .width = .grow }, .padding = .all(10) },
            .decoration = .{ .background = shell.palette.sunken, .corner_radius = .all(6) },
        });
        ui.text(writer.buffered(), .{ .size = 13 * shell.text_scale, .color = shell.palette.good, .font = 1 });
        ui.close();
    }
};

fn childColor(index: usize) zui.Color {
    return kit.hueColor(0.55 + @as(f32, @floatFromInt(index)) * 0.13, 0.5, 0.95);
}
